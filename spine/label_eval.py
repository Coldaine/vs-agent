"""label_eval.py — G1.5 eval-set construction. No human play session.

Frames come from the reflex bot's own G1 runs. Labels are generated by
the leader-class model applying the rubric in docs/game_reference.md
section 6, then audited by a second model pass. Disagreements are
queued for the human in status/HUMAN_NEEDED.md (expected: a handful).

Usage: python spine/label_eval.py --frames episodes/ --n 100
"""

from __future__ import annotations
import argparse, glob, json, os, random
import model_client

# Prompts live in prompts/ (AGENTS.md convention — never inline):
RUBRIC_POINTER = None  # loaded from files in label_frames()


def label_frames(frames_dir: str, n: int):
    labeler_prompt = open("prompts/labeler.md").read()
    auditor_prompt = open("prompts/auditor.md").read()
    frames = sorted(glob.glob(os.path.join(frames_dir, "**", "*.jpg"),
                              recursive=True))
    sample = random.sample(frames, min(n, len(frames)))
    labels, disagreements = [], []
    for fp in sample:
        primary = model_client.call_labeler(fp, labeler_prompt)
        audit = model_client.call_auditor(fp, auditor_prompt, primary)
        if audit["agrees"]:
            labels.append({"frame": fp, **{k: primary[k] for k in
                          ("threat_octant", "gem_octant", "is_level_up",
                           "correct_action")}})
        else:
            disagreements.append({"frame": fp, "primary": primary,
                                  "audit": audit})
    os.makedirs("eval_set", exist_ok=True)
    json.dump(labels, open("eval_set/labels.json", "w"), indent=2)
    if disagreements:
        with open("status/HUMAN_NEEDED.md", "w") as f:
            f.write(f"{len(disagreements)} label disagreements need "
                    "adjudication. See eval_set/disagreements.json — "
                    "pick primary or audit for each, or mark skip.")
        json.dump(disagreements,
                  open("eval_set/disagreements.json", "w"), indent=2)
    print(json.dumps({"labeled": len(labels),
                      "disagreements": len(disagreements)}))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--frames", required=True)
    ap.add_argument("--n", type=int, default=100)
    label_frames(ap.parse_args().frames, ap.parse_args().n)
